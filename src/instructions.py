"""Render instructions and safely apply them to an explicit backend config dir.

Rendering is a cross-platform preview and performs no target writes. Applying
requires a matching host, an existing non-project target directory, and the
target-specific AGENTS.md receipt. The caller serializes writers and persists
the returned receipt; receipt and file updates are not a single transaction.
Prior managed content is backed up before an update, without overwriting any
existing backup. A failed update may leave that backup for explicit resolution.
"""

import hashlib
import os
from collections.abc import Iterable
from pathlib import Path, PureWindowsPath

from paths import detect_platform
from storage import (
    ManagedFileError,
    ManagedFileResult,
    ReceiptError,
    _existing,
    _outside_git,
    _parent,
    apply_file,
)


class InstructionsError(ValueError):
    """Invalid selection or unsafe instruction target."""


_COMPONENTS = ("slim", "ponytail", "engram", "cbm", "semgrep", "markitdown", "taskmd")


def render_instructions(
    source_dir: str | Path,
    platform: str,
    components: Iterable[str] = (),
    *,
    local_addition: str | None = None,
) -> str:
    """Render from setup/instructions; the explicit local text is not loaded from Git."""
    if platform not in ("linux", "wsl", "windows"):
        raise InstructionsError("unsupported instruction platform")
    if isinstance(components, (str, bytes)):
        raise InstructionsError("components must be an iterable of component IDs")
    try:
        selected = set(components)
    except TypeError:
        raise InstructionsError("invalid component selection") from None
    if selected - set(_COMPONENTS):
        raise InstructionsError("unknown instruction component")
    if local_addition is not None and not isinstance(local_addition, str):
        raise InstructionsError("local addition must be text")
    sources = ["common.md", "windows.md" if platform == "windows" else "linux.md"]
    if platform == "wsl":
        sources.append("wsl.md")
    sources.append("skills.md")
    sources.extend(f"components/{name}.md" for name in _COMPONENTS if name in selected)
    sections = ["<!-- GENERATED by workkit; edit the referenced sources, not this file. -->"]
    for source in sources:
        try:
            text = (Path(source_dir) / source).read_text(encoding="utf-8").strip()
        except (OSError, UnicodeError):
            raise InstructionsError("cannot read instruction source") from None
        if not text:
            raise InstructionsError("instruction source is empty")
        sections.append(f"<!-- Source: setup/instructions/{source} -->\n{text}")
    if local_addition is not None and local_addition.strip():
        sections.append("<!-- Source: local addition supplied by caller -->\n" + local_addition.strip())
    return "\n\n".join(sections) + "\n"


def apply_instructions(
    source_dir: str | Path,
    config_dir: str | Path,
    platform: str,
    components: Iterable[str] = (),
    *,
    receipt: str | None,
    dry_run: bool = False,
    local_addition: str | None = None,
) -> ManagedFileResult:
    """Apply AGENTS.md using its target-specific hash; preview via render_instructions.

    Updates create a private AGENTS.md.workkit-backup-<old SHA256>; a preexisting
    backup is a conflict, not permission to overwrite or adopt it. On dry-run no
    backup or target is written. No directories are created.
    """
    content = render_instructions(source_dir, platform, components, local_addition=local_addition).encode("utf-8")
    try:
        host = detect_platform().platform
    except ValueError:
        raise InstructionsError("unsupported host platform") from None
    if platform != host or (platform == "windows") != (os.name == "nt"):
        raise InstructionsError("cross-platform application is forbidden; render a preview instead")
    root = Path(config_dir)
    if (not root.is_absolute() or ".." in root.parts
            or (os.name == "posix" and (PureWindowsPath(str(config_dir)).drive or "\\" in str(config_dir)))):
        raise InstructionsError("config target must be an absolute native path")
    if os.name == "posix" and (root == Path("/etc/opencode") or Path("/etc/opencode") in root.parents):
        raise InstructionsError("system-wide config targets are not supported")
    try:
        with _parent(root / "AGENTS.md") as (fd, name):
            _outside_git(fd)
            previous = _existing(fd, name)
        planned = apply_file(root, "AGENTS.md", content, receipt, mode=0o600, dry_run=True)
        if not planned.changed:
            return planned
        if previous is not None:
            old = previous[0]
            if receipt is None or hashlib.sha256(old).hexdigest() != receipt:
                raise InstructionsError("managed instructions changed during preview")
            apply_file(root, "AGENTS.md.workkit-backup-" + receipt, old, None, mode=0o600, dry_run=dry_run)
        if dry_run:
            return planned
        return apply_file(root, "AGENTS.md", content, receipt, mode=0o600)
    except (ManagedFileError, ReceiptError, OSError):
        raise InstructionsError("cannot safely apply instructions; target or backup may conflict") from None
